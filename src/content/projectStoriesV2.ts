export function longStory(id: ProjectId): StoryEpisode[] | undefined {
  return LONG_STORIES[id as LongId]
}

export function longStoryDetail(id: ProjectId, choices: Record<string, string> | undefined, final: boolean): string {
  if (id === 'ideal-sofa') {
    const selection = choices?.['1']
    const detail = selection?.startsWith('Красивый') ? 'Красивый диван оказался удобным.' : selection?.startsWith('Загадочный') ? 'Под обивкой загадочного дивана нашлась забытая смешная записка.' : selection?.startsWith('Диван соседа') ? 'Сосед помог починить и занести свой старый диван.' : ''
    return final ? detail : ''
  }
  if (id === 'train-assistant' && final) return choices?.['2'] === 'Проверить рецепт' ? 'Проверка помогла заранее заметить ошибку ИИ.' : 'Маша заметила ошибку ИИ на кухне и исправила её.'
  if (id === 'goose-owner' && final) return choices?.['1'] === 'Сфотографировать гуся' ? 'Фотография помогла уточнить примету Пельменя.' : 'Опрошенный сосед помог найти Пельменя у магазина.'
  return ''
}
