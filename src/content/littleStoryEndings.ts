export function littleStoryEnding(id: LittleStoryId, choice: 0 | 1): string {
  if (id === 'little-48' && choice === 1) return 'Маша возвращается к совету и делает первый шаг. ИИ предлагает отпраздновать без отдельного плана празднования.'
  if (id === 'little-49') return choice === 0 ? 'ИИ обращается к Маше по имени и признаётся, что предыдущее обращение ему тоже нравилось.' : 'ИИ обращается к Маше «капитан проектов» и признаётся, что предыдущее обращение ему тоже нравилось.'
  if (id === 'little-44' && choice === 1) return 'На вопрос Маши ИИ отвечает: «Немного волнуюсь. Но могу напоминать и пореже».'
  const story = LITTLE_STORIES.find((item) => item.id === id)!
  return id === 'little-48' ? story.ending : `${CHOICE_DETAILS[id][choice]} ${story.ending}`
}
