import { expect, test } from './fixtures.ts'
import { createInitialGameState } from '../../src/game/state.ts'
import { createEventSession } from '../../src/game/eventSession.ts'
import { SAVE_KEY } from '../../src/storage/gameStorage.ts'

test('гусь ждёт выбора, восстановление не повторяет эффект и последний ход можно закончить', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.clock.install()
  const game = { ...createInitialGameState(), money: 0, sanity: 50, actionsRemaining: 1 }
  await page.addInitScript(({ key, game, events }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 20, game, events })) }, { key: SAVE_KEY, game, events: createEventSession() })
  await page.goto('/')
  await page.evaluate(() => { let count = 0; Math.random = () => ++count === 8 ? 0.1 : 0.99 })
  await page.getByRole('button', { name: 'Отдохнуть' }).click()
  const goose = page.getByRole('button', { name: 'Поговорить с гусём' })
  await expect(goose).toBeVisible()
  await goose.focus()
  await page.keyboard.press('Enter')
  let dialog = page.getByRole('dialog', { name: 'Гость с крыльями' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Гость с крыльями' })).toBeFocused()
  await page.clock.fastForward(25000)
  await expect(dialog).toBeVisible()
  await expect(page.locator('.room-item-goose')).toHaveCount(1)
  await expect(dialog.getByRole('button', { name: /Предложить угощение/ })).toBeDisabled()
  await expect(dialog.getByText('Не хватает монет: нужно 5.')).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.goose?.pending?.choice, SAVE_KEY)).toBeNull()
  await page.reload()
  dialog = page.getByRole('dialog', { name: 'Гость с крыльями' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: /Поговорить —/ }).click()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).game.achievements, SAVE_KEY)).toContain('goose')
  await expect(dialog.getByText(/обстоятельным «га»/)).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.goose?.pending?.choice, SAVE_KEY)).toBe('talk')
  const value = await page.getByRole('progressbar', { name: 'Кукуха' }).getAttribute('value')
  expect(value).toBe('63')
  await page.reload()
  dialog = page.getByRole('dialog', { name: 'Гость с крыльями' })
  await expect(dialog.getByText(/обстоятельным «га»/)).toBeVisible()
  await expect(page.getByRole('progressbar', { name: 'Кукуха' })).toHaveAttribute('value', '63')
  await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(goose).toHaveCount(0)
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await expect(page.getByText('День 2', { exact: true })).toBeVisible()
})
