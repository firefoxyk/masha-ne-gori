  await page.keyboard.press('Enter')
  await expect(dialog.getByText('Далее: Посадить семена — 1 действие, 5 энергии, 5 монет.')).toBeVisible()
  await expect(dialog.getByText('Нужно 5 монет.')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Посадить семена: Зелёный уголок' })).toBeDisabled()
  await dialog.locator('summary').filter({ hasText: 'Книга простых рецептов' }).click()
  await expect(dialog.getByText('Далее: продолжить — бесплатно.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Продолжить: Книга простых рецептов' }).click()
  await expect(dialog.getByText('Состояние: начат; шагов выполнено 0 из 2.')).toBeVisible()
