  await page.addInitScript(({ key, game, events }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 6, game, events })) }, { key: SAVE_KEY, game, events: createEventSession() })
  await page.goto('/')
  await page.getByRole('button', { name: 'Проекты Маши' }).click()
  const dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
