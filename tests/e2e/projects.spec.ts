import { expect, test } from './fixtures.ts'

test('проект проходит через обновление и день, доступен с клавиатуры на телефоне', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  const open = page.getByRole('button', { name: 'Проекты Маши' })
  await open.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Начать: Зелёный уголок' }).click()
  await expect(dialog.getByText('Состояние: начат; шагов выполнено 0 из 2')).toBeVisible()
  await dialog.getByRole('button', { name: 'Подготовить горшок: Зелёный уголок' }).click()
  await expect(dialog.getByText('Состояние: начат; шагов выполнено 1 из 2')).toBeVisible()
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await expect(open).toBeFocused()
  await page.reload()
  await open.click()
  await expect(dialog.getByText('Состояние: начат; шагов выполнено 1 из 2')).toBeVisible()
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await open.click()
  await dialog.getByRole('button', { name: 'Посадить семена: Зелёный уголок' }).click()
  await expect(dialog.getByText('Состояние: завершён')).toBeVisible()
  await expect(dialog.getByText(/Зелень посажена/).first()).toBeVisible()
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.reload()
  await open.click()
  await expect(dialog.getByText('Состояние: завершён')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})
