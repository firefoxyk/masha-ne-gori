import { expect, test } from './fixtures.ts'
import { createInitialGameState } from '../../src/game/state.ts'
import { createEventSession } from '../../src/game/eventSession.ts'
import { SAVE_KEY } from '../../src/storage/gameStorage.ts'

test('история ждёт после последнего действия, обновления и нового дня', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  const game = { ...createInitialGameState(), actionsRemaining: 1 }
  await page.addInitScript(({ game, events }) => { if (!localStorage.getItem('masha-ne-gori.save')) localStorage.setItem('masha-ne-gori.save', JSON.stringify({ version: 22, game, events })) }, { game, events: createEventSession() })
  await page.goto('/')
  await page.evaluate(() => { const values = [0.01, 0.01, 0.99, 0.99, 0.01, 0.01]; Math.random = () => values.shift() ?? 0.99 })
  await page.getByRole('button', { name: 'Поработать' }).click()
  const event = page.getByRole('dialog')
  await expect(event).toBeVisible()
  await event.getByRole('button').first().click()
  await event.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(event).toHaveCount(0)
  const queue = page.getByRole('button', { name: /Есть история/ })
  await expect(queue).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.storyQueue?.[0]?.id, SAVE_KEY)).toBeTruthy()
  const selected = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.storyQueue[0].id, SAVE_KEY)
  await page.reload()
  await expect(queue).toBeVisible()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.storyQueue[0].id, SAVE_KEY)).toBe(selected)
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await queue.focus()
  await page.keyboard.press('Enter')
  await expect(event).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.work?.pending?.eventId, SAVE_KEY)).toBe(selected)
  await event.getByRole('button').first().click()
  const afterChoice = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).game, SAVE_KEY)
  await page.reload()
  await expect(event.getByRole('button', { name: 'Продолжить игру' })).toBeVisible()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).game, SAVE_KEY)).toEqual(afterChoice)
  await event.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(queue).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('запланированный гусь ждёт закрытия события', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.install()
  await page.goto('/')
  await page.evaluate(() => { const values = [0.01, 0.01, 0.99, 0.99, 0.99, 0.99, 0.01]; Math.random = () => values.shift() ?? 0.99 })
  await page.getByRole('button', { name: 'Поработать' }).click()
  const event = page.getByRole('dialog')
  await expect(event).toBeVisible()
  await expect(page.getByRole('button', { name: 'Поговорить с гусём' })).toHaveCount(0)
  await page.clock.fastForward(25000)
  await event.getByRole('button').first().click()
  await event.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(page.getByRole('button', { name: 'Поговорить с гусём' })).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.gooseVisitDay, SAVE_KEY)).toBe(1)
  await page.reload()
  await page.evaluate(() => { let count = 0; Math.random = () => ++count === 8 ? 0.01 : 0.99 })
  await page.getByRole('button', { name: 'Отдохнуть' }).click()
  await expect(page.getByRole('button', { name: 'Поговорить с гусём' })).toHaveCount(0)
})
