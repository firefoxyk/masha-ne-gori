import { expect, test } from './fixtures.ts'
import { SAVE_KEY } from '../../src/storage/gameStorage.ts'

test('обычное и рабочее событие показываются по очереди и восстанавливаются', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('/')
  await page.evaluate(() => { const draws = [0, 0, 0.99, 0.99, 0, 0]; Math.random = () => draws.shift() ?? 0.99 })
  await page.getByRole('button', { name: 'Поработать' }).click()
  const ordinary = page.getByRole('dialog', { name: 'Список дел с характером' })
  await expect(ordinary).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect.poll(() => page.evaluate((key) => JSON.parse(localStorage.getItem(key) || '{}').events?.work?.pending?.eventId, SAVE_KEY)).toBe('work-01')
  await page.reload()
  await expect(ordinary).toBeVisible()
  await ordinary.getByRole('button', { name: 'Выбрать главное' }).click()
  await ordinary.getByRole('button', { name: 'Продолжить игру' }).click()
  const work = page.getByRole('dialog', { name: 'Маленькая просьба' })
  await expect(work).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await work.getByRole('button', { name: /уточним задачу/ }).click()
  await expect(work.getByText('Маша находит главное.')).toBeVisible()
  await expect(page.getByText('Осталось действий: 4')).toBeVisible()
  await expect.poll(() => page.evaluate((key) => JSON.parse(localStorage.getItem(key) || '{}').events?.work?.pending?.choiceId, SAVE_KEY)).toBe('option-1')
  await page.reload()
  await expect(work.getByText('Маша находит главное.')).toBeVisible()
  await work.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
