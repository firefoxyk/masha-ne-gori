test('магазин сохраняет покупки и лимит, не меняет итоги и переносит бонусы', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 700 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Закончить день' }).click()
  const summary = page.getByRole('region', { name: 'Итоги дня 1' })
  await expect(summary.getByText('Деньги', { exact: true }).locator('..').locator('dd')).toHaveText('100 (0)')
  await page.getByRole('button', { name: 'Заглянуть в магазин' }).click()
  let shop = page.getByRole('dialog', { name: 'Магазин уютных мелочей' })
  await expect(shop.getByRole('heading', { name: 'Магазин уютных мелочей' })).toBeFocused()
  await shop.locator('summary').filter({ hasText: 'Вкусняшки' }).click()
  await shop.getByRole('button', { name: 'Купить: Вкусняшка' }).click()
  await shop.getByRole('button', { name: 'Купить: Вкусняшка' }).click()
  await expect(shop.getByText('Расходуемые покупки: 2 из 2')).toBeVisible()
  await expect(shop.getByRole('button', { name: 'Купить: Вкусняшка' })).toBeDisabled()
  await shop.locator('summary').filter({ hasText: 'Уют' }).click()
  await shop.getByRole('button', { name: 'Купить: Мягкая подушка' }).click()
  await expect(shop.getByRole('button', { name: 'Куплено: Мягкая подушка' })).toBeDisabled()
  await expect(shop.getByText('Игровые монеты: 10')).toBeVisible()
  await shop.getByRole('button', { name: 'Вернуться к итогам' }).click()
  await expect(summary.getByText('Деньги', { exact: true }).locator('..').locator('dd')).toHaveText('100 (0)')
  await page.getByRole('button', { name: 'Заглянуть в магазин' }).click()
  await expect(page.getByRole('dialog').getByText('Игровые монеты: 10')).toBeVisible()
  await expect(page.getByRole('dialog').locator('summary').filter({ hasText: 'Уют' }).locator('..')).not.toHaveAttribute('open', '')
  await page.reload()
  await page.getByRole('button', { name: 'Заглянуть в магазин' }).click()
  shop = page.getByRole('dialog', { name: 'Магазин уютных мелочей' })
  await expect(shop.getByText('Игровые монеты: 10')).toBeVisible()
  await expect(shop.getByText('Расходуемые покупки: 2 из 2')).toBeVisible()
  await expect(shop.getByText(/Сейчас: сытость 90/)).toBeVisible()
  await shop.locator('summary').filter({ hasText: 'Уют' }).click()
  await expect(shop.getByRole('button', { name: 'Куплено: Мягкая подушка' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await shop.getByRole('button', { name: 'Начать следующий день' }).click()
  await expect(page.getByText('+23 энергии, +10 кукухи')).toBeVisible()
  await page.reload()
  await expect(page.getByText('+23 энергии, +10 кукухи')).toBeVisible()
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Заглянуть в магазин' }).click()
  await expect(page.getByRole('dialog').getByText('Расходуемые покупки: 0 из 2')).toBeVisible()
})

test('магазин доступен с клавиатуры и закрывается по Escape', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.keyboard.press('Tab')
  const opener = page.getByRole('button', { name: 'Заглянуть в магазин' })
  await expect(opener).toBeFocused()
  await page.keyboard.press('Enter')
  const shop = page.getByRole('dialog', { name: 'Магазин уютных мелочей' })
  await expect(shop).toBeVisible()
  await expect(shop.getByRole('heading', { name: 'Магазин уютных мелочей' })).toBeFocused()
  await page.keyboard.press('Tab')
  const treats = shop.locator('summary').filter({ hasText: 'Вкусняшки' })
  await expect(treats).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(treats.locator('..')).toHaveAttribute('open', '')
  await expect(shop.getByRole('button', { name: 'Купить: Вкусняшка' })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(treats.locator('..')).not.toHaveAttribute('open', '')
  const bounds = await shop.boundingBox()
  expect(bounds!.height).toBeLessThanOrEqual(568)
  await page.keyboard.press('Escape')
  await expect(shop).toHaveCount(0)
  await expect(opener).toBeFocused()
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await expect(page.getByText('День 2', { exact: true })).toBeVisible()
})

test('категории открываются независимо, показывают все товары и не обрезают навигацию', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Заглянуть в магазин' }).click()
  const shop = page.getByRole('dialog', { name: 'Магазин уютных мелочей' })
  const groups = [
    { name: 'Вкусняшки', products: ['Вкусняшка', 'Готовый ужин', 'Необычный напиток', 'Коробочка «побаловать себя»'] },
    { name: 'Уют', products: ['Маленькое растение', 'Свисающая лиана', 'Тёплая гирлянда', 'Мягкая подушка', 'Уютный плед', 'Удобное кресло', 'Уютный диван', 'Книжный шкаф'] },
    { name: 'Удобство', products: ['Любимая кружка', 'Настольная лампа', 'Второй монитор'] },
  ]
  for (const group of groups) {
    const summary = shop.locator('summary').filter({ hasText: group.name })
    await expect(summary.locator('..')).not.toHaveAttribute('open', '')
    await summary.click()
    await expect(summary.locator('..')).toHaveAttribute('open', '')
    for (const product of group.products) await expect(summary.locator('..').getByRole('heading', { name: product, exact: true })).toBeVisible()
  }
  await expect(shop.locator('details[open]')).toHaveCount(3)
  await expect(shop.getByText('Постоянно: Нет')).toHaveCount(0)
  await expect(shop.getByText('Не хватает монет: нужно 180.')).toBeVisible()
  const dialogBox = await shop.boundingBox()
  for (const label of ['Вернуться к итогам', 'Начать следующий день']) {
    const button = shop.getByRole('button', { name: label })
    await expect(button).toBeInViewport()
    const bounds = await button.boundingBox()
    expect(bounds!.height).toBeGreaterThanOrEqual(44)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(dialogBox!.y + dialogBox!.height)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await shop.locator('summary').filter({ hasText: 'Уют' }).click()
  await expect(shop.locator('details[open]')).toHaveCount(2)
  await shop.locator('summary').filter({ hasText: 'Вкусняшки' }).click()
  await shop.locator('summary').filter({ hasText: 'Удобство' }).click()
  await expect(shop.locator('details[open]')).toHaveCount(0)
})

