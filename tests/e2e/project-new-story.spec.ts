import { expect, test } from './fixtures.ts'
import { createInitialGameState } from '../../src/game/state.ts'
import { createEventSession } from '../../src/game/eventSession.ts'
import { SAVE_KEY } from '../../src/storage/gameStorage.ts'

test('подборка идей сохраняется после перезагрузки и не пополняется после запуска', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('/')
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  let dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
  let section = dialog.locator('#project-group-idea').locator('..')
  const ideas = await section.locator('summary').allTextContents()
  expect(ideas).toHaveLength(3)
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
  section = dialog.locator('#project-group-idea').locator('..')
  expect(await section.locator('summary').allTextContents()).toEqual(ideas)
  await section.locator('summary').first().click()
  await section.getByRole('button', { name: /^Начать:/ }).click()
  expect(await section.locator('summary').count()).toBe(2)
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  expect(await dialog.locator('#project-group-idea').locator('..').locator('summary').count()).toBe(2)
})

test('выбор стиля помощника и финал восстанавливаются на мобильном экране', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  const initial = createInitialGameState()
  const game = { ...initial, day: 11, unfinishedProjects: 1, projectIdeas: { day: 11, ids: ['ideal-sofa', 'goose-owner'] }, projects: { 'train-assistant': { status: 'started', step: 2, story: { scenario: 0, startDay: 1, seen: 10, actual: null, choices: { '2': 'Оставить как есть' } } } } }
  await page.addInitScript(({ key, game, events }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 9, game, events })) }, { key: SAVE_KEY, game, events: createEventSession() })
  await page.goto('/')
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  let dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
  await dialog.locator('summary').filter({ hasText: 'Обучить домашнего ИИ-помощника' }).click()
  await dialog.getByRole('button', { name: 'Смешной', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(dialog.getByText(/Выбран смешной стиль/).last()).toBeVisible()
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  dialog = page.getByRole('dialog', { name: 'Проекты Маши' })
  await dialog.locator('summary').filter({ hasText: 'Обучить домашнего ИИ-помощника' }).click()
  await expect(dialog.getByText(/Выбран смешной стиль/).last()).toBeVisible()
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  await dialog.locator('summary').filter({ hasText: 'Обучить домашнего ИИ-помощника' }).click()
  await dialog.getByRole('button', { name: /Прочитать событие: Обучить/ }).click()
  await expect(dialog.locator('#project-group-completed').locator('..').getByText(/Ваш организм отправил запрос на обед/)).toBeVisible()
  await expect(dialog.getByText(/Изменения: \+8 мотивации/).first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await dialog.getByRole('button', { name: 'Вернуться в игру' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Проекты Маши/ }).click()
  await dialog.locator('#project-group-completed').locator('..').locator('summary').filter({ hasText: 'Обучить домашнего ИИ-помощника' }).click()
  await expect(dialog.locator('#project-group-completed').locator('..').getByText(/Ваш организм отправил запрос на обед/)).toBeVisible()
  await expect(dialog.getByText(/Изменения: \+8 мотивации/).first()).toBeVisible()
  await expect(dialog.getByRole('button', { name: /Начать снова: Обучить/ })).toHaveCount(0)
  const journal = dialog.locator('#project-journal-title').locator('..')
  await journal.locator('summary').filter({ hasText: 'Обучить домашнего ИИ-помощника' }).click()
  await expect(journal.getByText(/Выборы:.*Смешной/)).toBeVisible()
  await expect(journal.getByText(/Изменения: \+8 мотивации/)).toBeVisible()
})
