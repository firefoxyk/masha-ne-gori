import { expect, test } from '@playwright/test'
import { createInitialGameState } from '../../src/game/state.ts'
import { SAVE_KEY } from '../../src/storage/gameStorage.ts'

for (const money of [0, 24]) {
  test(`бесплатный перекус при ${money} монетах можно отменить и восстановить`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 640 })
    const game = { ...createInitialGameState(), money, satiety: 40 }
    await page.addInitScript(({ key, game }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 2, game })); Math.random = () => 0.99 }, { key: SAVE_KEY, game })
    await page.goto('/')
    const eat = page.getByRole('button', { name: 'Поесть' })
    await expect(eat).toBeEnabled()
    await eat.click()
    const dialog = page.getByRole('dialog', { name: 'Как поест Маша?' })
    await expect(dialog.getByRole('button', { name: /Перекусить.*бесплатно.*\+15 сытости/ })).toBeVisible()
    await expect(page.getByText('Осталось действий: 5')).toBeVisible()
    await dialog.getByRole('button', { name: 'Вернуться без перекуса' }).click()
    await expect(page.getByText('Осталось действий: 5')).toBeVisible()
    await eat.click()
    await expect.poll(() => page.evaluate((key) => JSON.parse(localStorage.getItem(key) || '{}').events?.meal?.pending?.freeSnack, SAVE_KEY)).toBe(true)
    await page.reload()
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: /Перекусить/ }).click()
    await expect(page.getByRole('progressbar', { name: 'Сытость' })).toHaveAttribute('value', '55')
    await expect(page.getByText('Осталось действий: 4')).toBeVisible()
    await expect.poll(() => page.evaluate((key) => JSON.parse(localStorage.getItem(key) || '{}').events?.meal?.pending?.result?.id, SAVE_KEY)).toBe('snack')
    await page.reload()
    await expect(page.getByRole('progressbar', { name: 'Сытость' })).toHaveAttribute('value', '55')
    await expect(page.getByText('Осталось действий: 4')).toBeVisible()
    await expect(page.getByText('Деньги', { exact: true }).locator('..').locator('dd')).toHaveText(String(money))
    if (money === 0) await page.evaluate(() => { Math.random = () => 0 })
    await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
    if (money === 0) {
      const event = page.getByRole('dialog')
      await expect(event).toBeVisible()
      await event.locator('button:not(:disabled)').first().click()
      await event.getByRole('button', { name: 'Продолжить игру' }).click()
    }
    await page.getByRole('button', { name: 'Закончить день' }).click()
    await page.getByRole('button', { name: 'Начать следующий день' }).click()
    await expect(page.getByText('День 2', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

test('еда доступна на телефоне, восстанавливается и не списывается повторно', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  const game = { ...createInitialGameState(), money: 25, energy: 0, satiety: 60 }
  await page.addInitScript(({ key, game }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 2, game })) }, { key: SAVE_KEY, game })
  await page.goto('/')
  await page.evaluate(() => { const draws = [0.9, 0.9, 0.1]; Math.random = () => draws.shift() ?? 0.9 })
  await page.getByRole('button', { name: 'Поесть' }).click()
  const dialog = page.getByRole('dialog', { name: 'Как поест Маша?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('Нужно 5 энергии.')).toBeVisible()
  await expect(dialog.getByText('Нужно 40 монет.')).toBeVisible()
  await expect.poll(() => page.evaluate((key) => !!JSON.parse(localStorage.getItem(key) || '{}').events?.meal?.pending, SAVE_KEY)).toBe(true)
  await page.reload()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: /Перекусить/ }).focus()
  await page.keyboard.press('Enter')
  await expect(dialog.getByRole('heading', { name: /Еда:/ })).toBeFocused()
  await expect(dialog.getByText('Сытость: +15')).toBeVisible()
  const story = await dialog.locator('section p').first().textContent()
  await expect.poll(() => page.evaluate((key) => !!JSON.parse(localStorage.getItem(key) || '{}').events?.meal?.pending?.result, SAVE_KEY)).toBe(true)
  await page.reload()
  await expect(dialog.locator('section p').first()).toHaveText(story!)
  await expect(page.getByText('Осталось действий: 4')).toBeVisible()
  await expect(page.getByRole('progressbar', { name: 'Сытость' })).toHaveAttribute('value', '75')
  await expect(page.getByText('Деньги', { exact: true }).locator('..').locator('dd')).toHaveText('25')
  await page.evaluate(() => { Math.random = () => 0 })
  await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
  const event = page.getByRole('dialog')
  await expect(event).toBeVisible()
  await event.locator('button:not(:disabled)').first().click()
  await event.getByRole('button', { name: 'Продолжить игру' }).click()
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await expect(page.getByRole('region', { name: 'Итоги дня 1' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
