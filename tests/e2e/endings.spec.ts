test('старые покупки, два финала, обновление, отмена и подтверждение новой игры', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const initial = createInitialGameState()
  const game = { ...initial, day: 13, ownedItems: ['pillow'], projects: { 'goose-owner': { status: 'completed', step: 2 }, 'balcony-garden': { status: 'completed', step: 2 } } }
  const events = { ...createEventSession(), storyQueue: [{ type: 'work', id: 'work-01' }] }
  await page.addInitScript(({ key, game, events }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 6, game, events })) }, { key: SAVE_KEY, game, events })
  await page.goto('/')
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await expect(page.getByText(/Доступна история прохождения/)).toBeVisible()
  await page.reload()
  await expect(page.getByText(/Доступна история прохождения/)).toBeVisible()
  await page.locator('.ending-options summary').focus()
  await page.keyboard.press('Enter')
  await page.locator('.ending-options').screenshot({ path: '.cache/screens/ending-offer.png' })
  await expect(page.getByRole('button', { name: 'Посмотреть завершение: Место для себя' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Посмотреть завершение: Гусиные полномочия' })).toBeVisible()
  await page.getByRole('button', { name: 'Посмотреть завершение: Место для себя' }).click()
  let dialog = page.getByRole('dialog', { name: 'Место для себя' })
  await expect(dialog.getByRole('heading')).toBeFocused()
  await page.screenshot({ path: '.cache/screens/ending-home.png' })
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).events.endingsSeen, SAVE_KEY)).toEqual(['home'])
  await page.reload()
  await page.locator('.ending-options summary').click()
  await page.getByRole('button', { name: 'Посмотреть снова: Место для себя' }).click()
  dialog = page.getByRole('dialog', { name: 'Место для себя' })
  await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
  await page.getByRole('button', { name: 'Посмотреть завершение: Гусиные полномочия' }).click()
  dialog = page.getByRole('dialog', { name: 'Гусиные полномочия' })
  await page.screenshot({ path: '.cache/screens/ending-goose.png' })
  await page.addStyleTag({ content: 'html { font-size: 160%; }' })
  await dialog.getByRole('button', { name: 'Начать новую игру' }).click()
  await expect(dialog.getByText(/Текущее прохождение будет сброшено/)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog.getByRole('button', { name: 'Начать новую игру' })).toBeFocused()
  await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(page.getByText(/Доступна история прохождения/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Начать следующий день' }).click()
  await expect(page.getByRole('button', { name: /Есть история/ })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Купленная подушка на кровати' })).toBeVisible()
  await page.getByRole('button', { name: 'Закончить день' }).click()
  await page.locator('.ending-options summary').click()
  await page.getByRole('button', { name: 'Посмотреть снова: Гусиные полномочия' }).click()
  dialog = page.getByRole('dialog', { name: 'Гусиные полномочия' })
  await dialog.getByRole('button', { name: 'Начать новую игру' }).click()
  await dialog.getByRole('button', { name: 'Да, начать новую игру' }).click()
  await expect(page.getByText('День 1', { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).game.ownedItems, SAVE_KEY)).toEqual([])
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).game.achievements, SAVE_KEY)).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
