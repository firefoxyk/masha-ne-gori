import { expect, test } from '@playwright/test'

test('выбор отдыха и результат восстанавливаются на телефоне без повторного действия', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 700 })
  await page.goto('/')
  await page.evaluate(() => { const draws = [0.9, 0.9, 0.1]; Math.random = () => draws.shift() ?? 0.9 })
  await page.getByRole('button', { name: 'Отдохнуть' }).click()
  const dialog = page.getByRole('dialog', { name: 'Как отдохнёт Маша?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button')).toHaveCount(4)
  await expect(page.getByText('Осталось действий:')).toContainText('4')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('masha-ne-gori.save') || '{}').events?.rest?.pending !== undefined)).toBe(true)
  await page.reload()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: /Потрогать траву/ }).focus()
  await page.keyboard.press('Enter')
  await expect(dialog.getByRole('heading', { name: /Отдых:/ })).toBeFocused()
  await expect(dialog.getByText(/Энергия:/)).toBeVisible()
  const result = await dialog.locator('section p').first().textContent()
  await expect.poll(() => page.evaluate(() => !!JSON.parse(localStorage.getItem('masha-ne-gori.save') || '{}').events?.rest?.pending?.result)).toBe(true)
  await page.reload()
  await expect(dialog.locator('section p').first()).toHaveText(result!)
  await expect(page.getByText('Осталось действий:')).toContainText('4')
  await page.evaluate(() => { Math.random = () => 0 })
  await dialog.getByRole('button', { name: 'Продолжить игру' }).click()
  const event = page.getByRole('dialog')
  await expect(event).toBeVisible()
  await event.getByRole('button').first().click()
  await event.getByRole('button', { name: 'Продолжить игру' }).click()
  await expect(page.getByRole('button', { name: 'Закончить день' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
